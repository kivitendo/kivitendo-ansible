SELECT
  current_database() AS database_name,
  COALESCE(d.version::text, '') AS schema_version,
  COALESCE(d.coa, '') AS coa,
  COALESCE(d.closedto::text, '') AS closed_to,
  COALESCE(d.accounting_method, '') AS accounting_method,
  COALESCE(d.profit_determination, '') AS profit_determination,
  (SELECT count(*)::bigint FROM chart) AS chart_rows,
  (SELECT count(*)::bigint FROM chart WHERE charttype = 'A') AS account_rows,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.id)), md5('')) FROM chart x) AS chart_digest,
  (SELECT count(*)::bigint FROM acc_trans) AS acc_trans_rows,
  (SELECT COALESCE(min(transdate)::text, '') FROM acc_trans) AS first_transdate,
  (SELECT COALESCE(max(transdate)::text, '') FROM acc_trans) AS last_transdate,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.acc_trans_id)), md5('')) FROM acc_trans x) AS acc_trans_digest,
  (SELECT count(*)::bigint FROM ar) AS ar_rows,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.id)), md5('')) FROM ar x) AS ar_digest,
  (SELECT count(*)::bigint FROM ap) AS ap_rows,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.id)), md5('')) FROM ap x) AS ap_digest,
  (SELECT count(*)::bigint FROM gl) AS gl_rows,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.id)), md5('')) FROM gl x) AS gl_digest,
  (SELECT count(*)::bigint FROM customer) AS customer_rows,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.id)), md5('')) FROM customer x) AS customer_digest,
  (SELECT count(*)::bigint FROM vendor) AS vendor_rows,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.id)), md5('')) FROM vendor x) AS vendor_digest,
  (SELECT count(*)::bigint FROM parts) AS parts_rows,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.id)), md5('')) FROM parts x) AS parts_digest,
  (SELECT count(*)::bigint FROM oe) AS oe_rows,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.id)), md5('')) FROM oe x) AS oe_digest,
  (SELECT count(*)::bigint FROM orderitems) AS orderitems_rows,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.id)), md5('')) FROM orderitems x) AS orderitems_digest,
  (SELECT count(*)::bigint FROM delivery_orders) AS delivery_orders_rows,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.id)), md5('')) FROM delivery_orders x) AS delivery_orders_digest,
  (SELECT count(*)::bigint FROM delivery_order_items) AS delivery_order_items_rows,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.id)), md5('')) FROM delivery_order_items x) AS delivery_order_items_digest,
  (SELECT count(*)::bigint FROM invoice) AS invoice_item_rows,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.id)), md5('')) FROM invoice x) AS invoice_item_digest,
  (SELECT count(*)::bigint FROM bank_transactions) AS bank_transactions_rows,
  (SELECT COALESCE(md5(string_agg(md5(row_to_json(x)::text), '' ORDER BY x.id)), md5('')) FROM bank_transactions x) AS bank_transactions_digest,
  md5(row_to_json(d)::text) AS defaults_digest
FROM defaults d
LIMIT 1;
